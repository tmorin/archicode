/**
 * Wave 030, run 0216: the Commands part of the manual says what the program says. Between two marker lines (attribute
 * entries, which Asciidoctor does not print; a line that starts with // is a draft line, which the manual does not
 * allow) the manual holds the usage message of the root command and of every command under it, as picocli prints it,
 * and this test builds that block from the live command line. With {@code ARCHICODE_MANUAL_REGENERATE=1} it writes the
 * block (the one place that writes); without it, it compares. The hand-written lines that name commands and options are held to the same
 * command line, in both modes: the list at the top of the part (b), the command lines of the listings (c) and the
 * options in the code spans (d).
 *
 * <p>{@code ARCHICODE_MANUAL_PATH} names the manual to read and, with the regenerate variable, to write.
 */
@Slf4j
@QuarkusTest
class CommandReferenceTest {

    static final String BEGIN = ":command-reference-begin: BEGIN generated by CommandReferenceTest, do not edit";
    static final String END = ":command-reference-end: END generated by CommandReferenceTest";
    static final String LISTING = "----";
    static final String COMMANDS_PART = "== Commands";
    static final String REGENERATE =
        "to regenerate the block, run: ARCHICODE_MANUAL_REGENERATE=1 JAVA_HOME=<jdk 25> ./mvnw test -Dtest=CommandReferenceTest";

    /** The words that look like an option in a code span of the Commands part and are not one, each with its reason. */
    static final Map<String, String> NOT_OPTIONS = Map.of(
        "-SNAPSHOT",
        "the suffix of a version (1.2.0-SNAPSHOT), not an option"
    );

    private static final Pattern BULLET = Pattern.compile("^- `([a-z-]+)`: (.*)$");
    private static final Pattern LINK = Pattern.compile("<<([^>,]+)(?:,[^>]*)?>>");
    private static final Pattern ANCHOR = Pattern.compile("\\[\\[([^\\],]+)(?:,[^\\]]*)?]]|\\[#([^\\],.%]+)[^\\]]*]");
    private static final Pattern IMAGE = Pattern.compile("ghcr\\.io/tmorin/archicode(?::\\S+)?\\s+(.*)");
    private static final Pattern CODE_SPAN = Pattern.compile("`(--?[A-Za-z][\\w-]*)[^`]*`");
    private static final Pattern QUOTED = Pattern.compile("'[^']*'|\"[^\"]*\"");

    /** A command of the tree: its path with the root named archicode, its command line and the usage it prints. */
    record Command(String path, CommandLine commandLine, String usage) {}

    @Inject
    CommandLine.IFactory factory;

    @Test
    void theBlockOfTheManualIsTheUsageOfEveryCommand() {
        val commands = commands();
        val lines = manualLines();
        val markers = markers(lines);
        val generated = block(commands).lines().toList();
        if ("1".equals(System.getenv("ARCHICODE_MANUAL_REGENERATE"))) {
            val rewritten = new ArrayList<String>(lines.subList(0, markers[0] + 1));
            rewritten.addAll(generated);
            rewritten.addAll(lines.subList(markers[1], lines.size()));
            write(rewritten);
            if (log.isInfoEnabled()) {
                log.info("CommandReferenceTest rewrote the block of {} ({} commands)", manualPath(), commands.size());
            }
            return;
        }
        val current = lines.subList(markers[0] + 1, markers[1]);
        if (!generated.equals(current)) {
            fail(firstDifference(commands, generated, current));
        }
    }

    @Test
    void theListOfTheCommandsNamesTheCommandsOfTheFirstLevelWithTheirDescriptions() {
        val commands = commands();
        val lines = manualLines();
        val start = lines.indexOf(COMMANDS_PART);
        assertTrue(start >= 0, message("(b)", "the manual has no line `" + COMMANDS_PART + "`"));
        val defined = anchors(lines);
        val bullets = new LinkedHashMap<String, String>();
        val problems = new ArrayList<String>();
        for (
            var i = start + 1;
            i < lines.size() && !lines.get(i).startsWith("[[") && !lines.get(i).startsWith("==");
            i++
        ) {
            val bullet = BULLET.matcher(lines.get(i));
            if (!bullet.matches()) {
                continue;
            }
            val name = bullet.group(1);
            val text = bullet.group(2);
            bullets.put(name, normalize(text.contains(" (see") ? text.substring(0, text.lastIndexOf(" (see")) : text));
            val link = LINK.matcher(text);
            while (link.find()) {
                if (!defined.contains(link.group(1))) {
                    problems.add("`" + name + "` links <<" + link.group(1) + ">>, which is no id of the manual");
                }
            }
        }
        val firstLevel = new LinkedHashMap<String, Command>();
        for (val command : commands) {
            val path = command.path().split(" ");
            if (path.length == 2) {
                firstLevel.put(path[1], command);
            }
        }
        if (!firstLevel.keySet().equals(bullets.keySet())) {
            problems.add("the list names " + bullets.keySet() + ", the program has " + firstLevel.keySet());
        }
        firstLevel.forEach((name, command) -> {
            val description = command.commandLine().getCommandSpec().usageMessage().description();
            val expected = normalize(description.length == 0 ? "" : description[0]);
            if (bullets.containsKey(name) && !expected.equals(bullets.get(name))) {
                problems.add(
                    "`" +
                        name +
                        "` is described as \"" +
                        bullets.get(name) +
                        "\", the program says \"" +
                        expected +
                        "\""
                );
            }
        });
        if (!problems.isEmpty()) {
            fail(message("(b)", "the list at the top of `" + COMMANDS_PART + "`: " + String.join("; ", problems)));
        }
    }

    @Test
    void everyCommandLineOfTheListingsNamesACommandAndOptionsTheProgramHas() {
        val commands = commands();
        val lines = manualLines();
        val problems = new ArrayList<String>();
        var inListing = false;
        for (val index : handWritten(lines)) {
            val line = lines.get(index);
            if (LISTING.equals(line)) {
                inListing = !inListing;
                continue;
            }
            if (!inListing) {
                continue;
            }
            String rest = null;
            if (line.startsWith("archicode ")) {
                rest = line.substring("archicode ".length());
            } else {
                val image = IMAGE.matcher(line);
                if (image.find()) {
                    rest = image.group(1);
                }
            }
            if (rest != null) {
                problems.addAll(commandLineProblems(commands, rest, index + 1));
            }
        }
        if (!problems.isEmpty()) {
            fail(
                message(
                    "(c)",
                    "a listing of the manual shows a command line the program does not have: " +
                        String.join("; ", problems)
                )
            );
        }
    }

    @Test
    void everyOptionInACodeSpanOfTheCommandsPartIsAnOptionOfSomeCommand() {
        val commands = commands();
        val lines = manualLines();
        val known = new TreeSet<String>();
        for (val command : commands) {
            for (val option : command.commandLine().getCommandSpec().options()) {
                known.addAll(List.of(option.names()));
            }
        }
        val start = lines.indexOf(COMMANDS_PART);
        assertTrue(start >= 0, message("(d)", "the manual has no line `" + COMMANDS_PART + "`"));
        var end = start + 1;
        while (end < lines.size() && !(lines.get(end).startsWith("== ") && !lines.get(end).startsWith("=== "))) {
            end++;
        }
        val handWritten = new LinkedHashSet<>(handWritten(lines));
        val problems = new ArrayList<String>();
        var inListing = false;
        for (var i = start + 1; i < end; i++) {
            if (LISTING.equals(lines.get(i))) {
                inListing = !inListing;
            }
            if (inListing || !handWritten.contains(i)) {
                continue;
            }
            val span = CODE_SPAN.matcher(lines.get(i));
            while (span.find()) {
                val name = span.group(1);
                if (!known.contains(name) && !NOT_OPTIONS.containsKey(name)) {
                    problems.add("line " + (i + 1) + " writes `" + name + "`");
                }
            }
        }
        if (!problems.isEmpty()) {
            fail(
                message(
                    "(d)",
                    "a code span of `" +
                        COMMANDS_PART +
                        "` names an option no command has: " +
                        String.join("; ", problems)
                )
            );
        }
    }

    /** The tree, root first, then depth first in declaration order, on a command line of the test's own. */
    private List<Command> commands() {
        val root = new CommandLine(ArchiCode.class, factory);
        root.setCommandName("archicode");
        val commands = new ArrayList<Command>();
        walk(root, "archicode", commands);
        return commands;
    }

    private void walk(CommandLine commandLine, String path, List<Command> commands) {
        val usageMessage = commandLine.getCommandSpec().usageMessage();
        assertEquals(80, usageMessage.width(), message("(a)", "the usage width of `" + path + "` is not 80 columns"));
        assertFalse(usageMessage.hidden(), message("(a)", "`" + path + "` is hidden, and the block is every command"));
        commands.add(new Command(path, commandLine, usage(path, commandLine)));
        Set<CommandLine> seen = Collections.newSetFromMap(new IdentityHashMap<>());
        for (val sub : commandLine.getSubcommands().values()) {
            if (seen.add(sub)) {
                walk(sub, path + " " + sub.getCommandName(), commands);
            }
        }
    }

    private String usage(String path, CommandLine commandLine) {
        val usage = new ArrayList<String>();
        for (val line : commandLine.getUsageMessage(CommandLine.Help.Ansi.OFF).split("\n", -1)) {
            val stripped = line.stripTrailing();
            assertFalse(
                LISTING.equals(stripped),
                message("(a)", "the usage of `" + path + "` has a line that closes a listing")
            );
            usage.add(stripped);
        }
        while (!usage.isEmpty() && usage.get(usage.size() - 1).isEmpty()) {
            usage.remove(usage.size() - 1);
        }
        return String.join("\n", usage) + "\n";
    }

    /** The lines between the two markers: one titled listing per command, each followed by a blank line. */
    private String block(List<Command> commands) {
        val block = new StringBuilder();
        for (val command : commands) {
            block.append('.').append(command.path()).append('\n');
            block.append(LISTING).append('\n').append(command.usage()).append(LISTING).append("\n\n");
        }
        return block.toString();
    }

    private String firstDifference(List<Command> commands, List<String> generated, List<String> current) {
        val expected = new LinkedHashMap<String, String>();
        commands.forEach(command -> expected.put(command.path(), command.usage()));
        val found = listings(current);
        for (val path : expected.keySet()) {
            if (!found.containsKey(path)) {
                return message("the block has no listing for the command `" + path + "`");
            }
        }
        for (val path : found.keySet()) {
            if (!expected.containsKey(path)) {
                return message("the block has a listing for `" + path + "`, which is no command of the program");
            }
        }
        if (!List.copyOf(expected.keySet()).equals(List.copyOf(found.keySet()))) {
            return message("the commands of the block are not in the order of the program: " + found.keySet());
        }
        for (val path : expected.keySet()) {
            if (!expected.get(path).equals(found.get(path))) {
                return message(
                    "the usage of the command `" +
                        path +
                        "` differs. The program prints:\n" +
                        expected.get(path) +
                        "The block has:\n" +
                        found.get(path)
                );
            }
        }
        for (var i = 0; i < Math.min(generated.size(), current.size()); i++) {
            if (!generated.get(i).equals(current.get(i))) {
                return message(
                    "the block differs from the generated one at its line " + (i + 1) + ": \"" + current.get(i) + "\""
                );
            }
        }
        return message("the block has " + current.size() + " lines, the generated one " + generated.size());
    }

    /** The titled listings of a block, by title (the command path), each with its text. */
    private Map<String, String> listings(List<String> block) {
        val listings = new LinkedHashMap<String, String>();
        for (var i = 0; i + 1 < block.size(); i++) {
            if (block.get(i).startsWith(".archicode") && LISTING.equals(block.get(i + 1))) {
                val text = new StringBuilder();
                var j = i + 2;
                for (; j < block.size() && !LISTING.equals(block.get(j)); j++) {
                    text.append(block.get(j)).append('\n');
                }
                listings.putIfAbsent(block.get(i).substring(1), text.toString());
                i = j;
            }
        }
        return listings;
    }

    /** The problems of one command line of a listing (what comes after the word archicode). */
    private List<String> commandLineProblems(List<Command> commands, String line, int number) {
        var rest = line;
        for (val cut : List.of(" #", " > ", " | ", " >")) {
            val at = rest.indexOf(cut);
            if (at >= 0) {
                rest = rest.substring(0, at);
            }
        }
        val tokens = QUOTED.matcher(rest).replaceAll("''").trim().split("\\s+");
        var current = commands.get(0);
        val options = new ArrayList<String>();
        val problems = new ArrayList<String>();
        // 0: no value is expected, 1: the next word is the value of an option, 2: it may be (an option of arity 0..*, which a command name ends)
        var skip = 0;
        for (val token : tokens) {
            if (token.isEmpty() || isValue(current, token, skip)) {
                skip = 0;
            } else if (token.startsWith("-")) {
                val name = token.contains("=") ? token.substring(0, token.indexOf('=')) : token;
                options.add(name);
                val option = option(current, name);
                skip = 0;
                if (!token.contains("=") && option != null && option.arity().max() > 0) {
                    skip = option.arity().min() > 0 ? 1 : 2;
                }
            } else if (current.commandLine().getSubcommands().containsKey(token)) {
                current = byPath(commands, current, token);
            } else if (current.commandLine().getCommandSpec().positionalParameters().isEmpty()) {
                problems.add("line " + number + ": `" + token + "` is no command under `" + current.path() + "`");
            }
        }
        for (val name : options) {
            if (option(current, name) == null) {
                problems.add("line " + number + ": `" + current.path() + "` has no option `" + name + "`");
            }
        }
        return problems;
    }

    private boolean isValue(Command current, String token, int expected) {
        return (
            expected == 1 ||
            (expected == 2 && !token.startsWith("-") && !current.commandLine().getSubcommands().containsKey(token))
        );
    }

    private Command byPath(List<Command> commands, Command parent, String name) {
        val path = parent.path() + " " + name;
        return commands
            .stream()
            .filter(command -> command.path().equals(path))
            .findFirst()
            .orElseThrow();
    }

    private CommandLine.Model.OptionSpec option(Command command, String name) {
        for (val option : command.commandLine().getCommandSpec().options()) {
            if (List.of(option.names()).contains(name)) {
                return option;
            }
        }
        return null;
    }

    /** The indexes of the lines that a person wrote: all of them, but the ones between the markers. */
    private List<Integer> handWritten(List<String> lines) {
        val begin = lines.indexOf(BEGIN);
        val end = lines.indexOf(END);
        val indexes = new ArrayList<Integer>();
        for (var i = 0; i < lines.size(); i++) {
            if (begin < 0 || end < begin || i <= begin || i >= end) {
                indexes.add(i);
            }
        }
        return indexes;
    }

    private Set<String> anchors(List<String> lines) {
        val anchors = new LinkedHashSet<String>();
        for (val line : lines) {
            val matcher = ANCHOR.matcher(line);
            while (matcher.find()) {
                anchors.add(matcher.group(1) != null ? matcher.group(1) : matcher.group(2));
            }
        }
        return anchors;
    }

    /** The lines of the two markers: each once, the first before the last. */
    private int[] markers(List<String> lines) {
        val begin = lines.stream().filter(BEGIN::equals).count();
        val end = lines.stream().filter(END::equals).count();
        assertEquals(
            1L,
            begin,
            message("(a)", "the manual must hold the marker line `" + BEGIN + "` once, it holds it " + begin + " times")
        );
        assertEquals(
            1L,
            end,
            message("(a)", "the manual must hold the marker line `" + END + "` once, it holds it " + end + " times")
        );
        val at = new int[] { lines.indexOf(BEGIN), lines.indexOf(END) };
        assertTrue(at[0] < at[1], message("(a)", "the marker `" + END + "` comes before the marker `" + BEGIN + "`"));
        return at;
    }

    private String normalize(String text) {
        return text.replaceAll("\\s+", " ").replaceAll("\\.$", "").trim();
    }

    private String message(String detail) {
        return message("(a)", detail);
    }

    private String message(String check, String detail) {
        return "CommandReferenceTest " + check + ": " + detail + "; " + REGENERATE;
    }

    private Path manualPath() {
        val path = System.getenv("ARCHICODE_MANUAL_PATH");
        return Path.of(path == null || path.isBlank() ? "src/doc/README.adoc" : path);
    }

    @SneakyThrows
    private List<String> manualLines() {
        return Files.readString(manualPath(), StandardCharsets.UTF_8).lines().toList();
    }

    @SneakyThrows
    private void write(List<String> lines) {
        Files.writeString(manualPath(), String.join("\n", lines) + "\n", StandardCharsets.UTF_8);
    }
}
