package io.morin.archicode.cli;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.morin.archicode.Warnings;
import io.quarkus.test.junit.QuarkusTest;
import jakarta.inject.Inject;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import lombok.SneakyThrows;
import lombok.val;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/**
 * The warnings of the application reach the error output of the command (wave 010, issue #35): the log level is
 * {@code ERROR}, which hides {@code log.warn}.
 */
@QuarkusTest
class WarningsChannelTest {

    private static final Path OLD_DIALECT = Path.of("src/test/resources/viewpoint-kernel/workspace");

    private static final String STORY_WORKSPACE = """
    application:
      elements:
        - kind: "solution"
          id: "sol_a"
          elements:
            - kind: "system"
              id: "sys_aa"
    views:
      - id: "sol_overview"
        name: "Sol A — Overview"
        viewpoint: "overview"
        layer: "application"
        properties:
          element: "sol_a"
      - id: "the_map"
        name: "Matrix of Sol A"
        viewpoint: "matrix"
        layer: "application"
        properties:
          pinned:
            - "sol_a"
    stories:
      - id: "tour"
        name: "Tour"
        steps:
          - view: "sol_overview"
          - view: "nobody_declared_this"
    """;

    @Inject
    CommandLine.IFactory factory;

    @Inject
    ErrorOutput errorOutput;

    @Inject
    Warnings warnings;

    @TempDir
    Path dir;

    private CliHarness.Result run(String... args) {
        return CliHarness.run(factory, errorOutput, args);
    }

    @Test
    void aSentenceSaidManyTimesIsPrintedOnceAndInTheOrderItWasSaid() {
        warnings.drain();
        warnings.warn("first");
        warnings.warn("second %s", "one");
        warnings.warn("first");
        warnings.warnAll(List.of("third", "second one"));
        assertEquals(List.of("warning: first", "warning: second one", "warning: third"), warnings.drain());
        assertEquals(List.of(), warnings.drain());
    }

    @Test
    @SneakyThrows
    void aFacetInTheOldDialectIsToldOnTheErrorOutputOfViewsGenerate() {
        copy(OLD_DIALECT, dir);
        val result = run("-w", dir.resolve("workspace.yaml").toString(), "views", "generate");
        assertEquals(0, result.exit(), result.err());
        // one line per rewritten filter, each once although the facet is applied to more than one workspace
        val lines = result.err().lines().toList();
        assertEquals(5, lines.size(), result.err());
        assertTrue(lines.stream().allMatch(line -> line.startsWith("warning: facet ")), result.err());
        assertTrue(
            lines.contains(
                "warning: facet no-smtp: deprecated facet syntax `@.qualifiers anyof ['SMTP']`: write `@.qualifiers[?(@ == 'SMTP')]`"
            ),
            result.err()
        );
        assertEquals("", result.out());
    }

    @Test
    @SneakyThrows
    void aStoryStepOnAViewNobodyDeclaredAndASkippedViewpointAreToldToo() {
        val workspace = Files.writeString(dir.resolve("workspace.yaml"), STORY_WORKSPACE);
        val result = run("-w", workspace.toString(), "views", "generate", "-i", "sol_overview", "-i", "the_map");
        assertEquals(0, result.exit(), result.err());
        assertEquals(
            List.of(
                "warning: the story `tour` has a step on the view `nobody_declared_this`, which is not declared",
                "warning: skip `the_map`: the viewpoint `matrix` is not generated by the command line"
            ),
            result.err().lines().toList()
        );
    }

    @Test
    @SneakyThrows
    void theWarningsComeBeforeTheErrorWhenTheCommandFails() {
        // the story is read before the references are drawn: the warning is said, then the command fails
        val workspace = Files.writeString(
            dir.resolve("workspace.yaml"),
            STORY_WORKSPACE.replace(
                "id: \"sys_aa\"",
                "id: \"sys_aa\"\n          relationships:\n            - destination: \"nowhere\"\n              label: \"uses\""
            )
        );
        val result = run("-w", workspace.toString(), "views", "generate", "-i", "sol_overview");
        assertEquals(1, result.exit(), result.err());
        val lines = result.err().lines().toList();
        assertEquals(2, lines.size(), result.err());
        assertTrue(lines.get(0).startsWith("warning: the story `tour`"), result.err());
        assertEquals("error: dangling reference: nowhere", lines.get(1));
    }

    @Test
    @SneakyThrows
    void aWorkspaceWithNothingToSayPrintsNothingOnTheErrorOutput() {
        val workspace = Files.writeString(
            dir.resolve("workspace.yaml"),
            STORY_WORKSPACE.replace("      - view: \"nobody_declared_this\"\n", "")
        );
        val result = run("-w", workspace.toString(), "views", "generate", "-i", "sol_overview");
        assertEquals(0, result.exit(), result.err());
        assertEquals("", result.err());
        assertEquals("", result.out());
    }

    @SneakyThrows
    private static void copy(Path from, Path to) {
        try (val files = Files.walk(from)) {
            for (val source : files.toList()) {
                val target = to.resolve(from.relativize(source).toString());
                if (Files.isDirectory(source)) {
                    Files.createDirectories(target);
                } else {
                    Files.copy(source, target);
                }
            }
        }
    }
}
