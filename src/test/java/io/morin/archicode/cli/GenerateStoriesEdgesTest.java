package io.morin.archicode.cli;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

import io.quarkus.test.junit.QuarkusTest;
import jakarta.inject.Inject;
import java.nio.file.Files;
import java.nio.file.Path;
import lombok.SneakyThrows;
import lombok.val;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import picocli.CommandLine;

/**
 * {@code archicode stories generate} on the workspace {@code archicode init} writes: the steps it cannot draw are skipped
 * with a warning that says which step and why, the run goes on, and a story that is not there is one error line.
 */
@QuarkusTest
class GenerateStoriesEdgesTest {

    @Inject
    CommandLine.IFactory factory;

    @Inject
    ErrorOutput errorOutput;

    @TempDir
    Path dir;

    Path workspace;

    @BeforeEach
    void init() {
        workspace = dir.resolve(".archicode.yaml");
        assertEquals(0, CliHarness.run(factory, errorOutput, "init", dir.toString()).exit());
    }

    @SneakyThrows
    private void story(String id, String steps) {
        Files.writeString(
            dir.resolve("manifests/story." + id + ".yaml"),
            "header:\n  kind: \"archicode.morin.io/story\"\n  version: \"1\"\ncontent:\n  id: \"" + id + "\"\n" + steps
        );
    }

    private CliHarness.Result stories(String... more) {
        val args = new java.util.ArrayList<>(java.util.List.of("-w", workspace.toString(), "stories", "generate"));
        args.addAll(java.util.List.of(more));
        return CliHarness.run(factory, errorOutput, args.toArray(String[]::new));
    }

    @Test
    void aWorkspaceWithoutStoryDrawsNothingAndSaysSo() {
        val result = stories();
        assertEquals(0, result.exit(), result.err());
        assertEquals("warning: the workspace has no story: nothing is drawn\n", result.err());
        assertFalse(Files.exists(dir.resolve("views-stories")));
    }

    @Test
    void aStoryThatIsAskedForButThereIsNoneIsOneErrorLine() {
        val result = stories("--story", "tour");
        assertEquals(1, result.exit());
        assertEquals("error: no story `tour` in the workspace (it has none)\n", result.err());
    }

    @Test
    void aStepIsSkippedWhenItNamesAViewNobodyDeclares() {
        story(
            "tour",
            """
              steps:
                - view: "ghost"
                - viewpoint: "overview"
                  properties:
                    element: "shop"
            """
        );
        val result = stories();
        assertEquals(0, result.exit(), result.err());
        assertEquals(
            "warning: the story `tour` has a step on the view `ghost`, which is not declared\n" +
                "warning: skip tour/1: the view `ghost` is not declared\n",
            result.err()
        );
        assertFalse(Files.exists(dir.resolve("views-stories/tour/01-ghost")));
        assertTrue(
            Files.isRegularFile(dir.resolve("views-stories/tour/02-overview/plantuml/application/step_02.puml"))
        );
    }

    @Test
    void aStepIsSkippedWhenItCarriesNoViewpointAndNamesNoView() {
        story(
            "tour",
            """
              steps:
                - text: "nothing to draw"
            """
        );
        val result = stories();
        assertEquals(0, result.exit(), result.err());
        assertEquals("warning: skip tour/1: it names no view and carries no viewpoint\n", result.err());
    }

    @Test
    void aStepIsSkippedWhenItsViewpointIsNotOneTheCommandLineDraws() {
        story(
            "tour",
            """
              steps:
                - viewpoint: "sequence"
                  properties:
                    element: "shop"
            """
        );
        val result = stories();
        assertEquals(0, result.exit(), result.err());
        assertEquals(
            "warning: skip tour/1: the viewpoint `sequence` is not generated by the command line\n",
            result.err()
        );
    }
}
